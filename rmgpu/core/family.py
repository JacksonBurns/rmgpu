"""
Family loader + KineticsFamilies facade (job-05/step-04).

Loads RMG's reaction-family definitions - templates, group trees, recipes,
and the reverse-family bookkeeping - and exposes the object the core loop
(job 06) asks for families, templates, and matching:

  - Family: one family's data - name, recipes (ReactionRecipe objects),
    templates (step-03's group tree: entries + top + forward_template,
    the shape core/template.py's match() consumes), rate rules (stored as
    DATA - see below), forbidden structures (as DATA), the reverse-family
    bookkeeping (reverse / reversible / own_reverse / reverse_map) and the
    effective reactant/product counts.
  - KineticsFamilies: loads all families of a named set (the 'default'
    recommended set) or a list of family names, and offers
    get_family(name), .families, match_reaction(reaction),
    get_families_of_reaction(reaction), and .blocked.

Source + the controlled parse
-----------------------------
Per the job-02 step-4 decision (reports/job-02-step-04-kineticsdb.md) the
family definitions ARE stored in rmgdb (kinetics_families_table: 129
families with template/recipe/reverse_map/reactant_num/product_num/
auto_generated; kinetics_family_groups_table: 8502 groups with their
adjacency lists; kinetics_family_rules_table). This loader's PRIMARY source
is therefore a controlled parse of the RMG-database family files
(<families>/<name>/groups.py, and rules.py for the rate-rule data):

  - groups.py carries EVERYTHING the loader needs - template(...),
    recipe(...), the bare flag assignments, entry(...) groups, the tree(...)
    hierarchy, and forbidden(...) structures - in RMG-Py's own file format.
    It is executed in a controlled namespace (the same mechanism rmgdb's own
    build and RMG-Py's Database.load use), so no DSL is re-invented.
  - rmgdb is used to CROSS-CHECK the parse: template/recipe/reverse_map/
    reactant_num/product_num/auto_generated must agree with the
    kinetics_families_table row, and every parsed group label/adjacency
    list must agree with the kinetics_family_groups_table row. Any
    disagreement is a load error (the two sources are built from the same
    files and must not drift).

Why the file parse is primary (documented finding, see
reports/job-05-step-04-families.md): rmgdb's
kinetics_family_groups_tree_table is INCOMPLETE. rmgdb's build.py derives
the parent/child edges with common/tree_str_to_pairs.sketchy_conversion,
which crashes (IndexError: pop from empty list) on several families'
tree() strings and build.py swallows the exception - so those families'
edges are missing (measured: H_Abstraction 0 of 534 edges;
R_Addition_MultipleBond 0 of 1211; 21 of the 51 default families have a
gap, several of them 0). The parent/child
hierarchy is what the tree descent (most-specific template labels) needs,
so the loader reconstructs it with RMG-Py's own _load_tree semantics
(rmgpy/data/base.py: parent = parents[level-1]; top = no parent, in
first-appearance order) from the tree() string - verified 0 mismatches
against the step-03 recorded reference trees (H_Abstraction 536 nodes,
intra_H_migration 313, Intra_ene_reaction 29, R_Addition_MultipleBond's
real-DB subset).

Rate rules are DATA
-------------------
rules.py is parsed and attached to Family.rules as plain dicts (label,
rank, reversible, elementary_high_p, duplicate, the kinetics object's
type name + raw args). The RATE-RULE ESTIMATOR is deleted (PLAN 3 / PLAN
4: ML is the only estimator) - nothing in this module computes a rate
from the rules; they are stored for the depository/reverse-rate purposes
of job 08.

Blocked families
----------------
A family whose data format the loader cannot express goes to
KineticsFamilies.blocked ({name: {reason, construct, note}}) instead of
Family. The list is load-bearing for job 06 (it proceeds around them); it
is expected to stay empty for the 'default' set (validated in
tests/test_families.py against the recorded reference).
"""

