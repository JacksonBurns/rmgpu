def _parse_groups_file(path):
    """Execute one family's groups.py in a controlled namespace and return
    its raw data: template/recipe kwargs, the bare flag assignments, the
    entry(...) groups (file order), the tree(...) string, and the
    forbidden(...) structures. Raises FamilyLoadError on any exec failure."""
    cap = {
        'entries': [],          # [{index,label,group}] file order
        'template': None,
        'recipe': None,
        'tree': None,
        'forbidden': [],
        'flags': {},
    }

    def entry(*, index=None, label='', group='', kinetics=None, **kw):
        cap['entries'].append({'index': index, 'label': label,
                               'group': group})

    def template(**kw):
        cap['template'] = kw

    def recipe(**kw):
        cap['recipe'] = kw

    def tree(s):
        cap['tree'] = s

    def forbidden(**kw):
        cap['forbidden'].append(dict(kw))

    env = {'entry': entry, 'template': template, 'recipe': recipe,
           'tree': tree, 'forbidden': forbidden,
           'True': True, 'False': False, 'None': None}
    try:
        g = dict(env)
        with open(path) as f:
            src = f.read()
        exec(compile(src, str(path), 'exec'), g)
    except Exception as e:
        raise FamilyLoadError('groups.py exec failed for %s: %s: %s'
                              % (path, type(e).__name__, e))
    cap['flags'] = {k: g[k] for k in _FLAG_KEYS if k in g}
    for k in cap['flags']:
        pass  # (flags captured above; names kept in _FLAG_KEYS)
    return cap


def _parse_rules_file(path):
    """Execute one family's rules.py in a controlled namespace and return
    the rate rules as plain DATA: [{index, label, rank, reversible,
    elementary_high_p, duplicate, kinetics_kind, kinetics_args}]. The
    kinetics object is captured by name + raw constructor args - it is
    stored, never evaluated (the rate-rule estimator is deleted, PLAN 3)."""
    rules = []

    class _KineticsStub:
        def __init__(self, *args, **kwargs):
            self.args = args
            self.kwargs = kwargs

    names = ['Arrhenius', 'ArrheniusEP', 'ArrheniusBM', 'PDepArrhenius',
             'MultiPDepArrhenius', 'Lindemann', 'Troe', 'ThirdBody',
             'MultiArrhenius', 'Chebyshev', 'Marcus', 'KineticsData',
             'SurfaceArrhenius', 'SurfaceArrheniusBEP',
             'SurfaceChargeTransfer', 'ArrheniusChargeTransfer',
             'ArrheniusChargeTransferBM', 'StickingCoefficient',
             'StickingCoefficientBEP']
    stubs = {n: type(n, (_KineticsStub,), {}) for n in names}

    # RateUncertainty is nested inside ArrheniusBM's uncertainty= kwarg in
    # rules.py; the stub captures its raw args so the rule stays DATA (it is
    # never evaluated - the rate-rule estimator is deleted).
    class _RateUncertaintyStub(_KineticsStub):
        pass
    stubs['RateUncertainty'] = _RateUncertaintyStub

    def entry(*, index=None, label='', kinetics=None, shortDesc='',
              longDesc='', rank=None, allow_max_rate_violation=None,
              reversible=None, elementary_high_p=None, duplicate=None,
              **kw):
        rules.append({
            'index': index,
            'label': label,
            'rank': rank,
            'reversible': reversible,
            'elementary_high_p': elementary_high_p,
            'duplicate': duplicate,
            'kinetics_kind': type(kinetics).__name__ if kinetics else None,
            'kinetics_args': (getattr(kinetics, 'args', None),
                              getattr(kinetics, 'kwargs', None))
            if kinetics else None,
        })

    env = {'entry': entry}
    env.update(stubs)
    env['R'] = 8.314472  # RMG-Py constants.R (rate rules store raw data;
    # the value only matters if a constructor evaluates - they do not)
    env['True'] = True
    env['False'] = False
    env['None'] = None
    try:
        g = dict(env)
        with open(path) as f:
            src = f.read()
        exec(compile(src, str(path), 'exec'), g)
    except Exception:
        return None  # rules are data for job 08; a parse gap is recorded
                     # on the family (rules_error), not fatal
    return rules


def _load_tree(tree_str):
    """RMG-Py Database._load_tree (rmgpy/data/base.py), ported. Returns
    (children, parent, top):
      children: {label: [child labels]} (file order, parent->child order)
      parent:   {label: parent label or None}
      top:      labels with no parent, in first-appearance order.
    Faithful to RMG: parent = parents[level-1]; level must not exceed the
    stack depth (RMG raises DatabaseError on that); blank/comment lines
    are skipped. Comment stripping matches RMG's remove_comment_from_line
    (base.py) EXACTLY: only a C++-style '//' comment is cut. '#' is a
    legitimate character in tree labels (e.g. 'C_rad/H2/Cs\\H2\\Cs|Cs#O'),
    so it is NOT treated as a comment marker here."""
    parser = re.compile(r'^\s*L(?P<level>\d+)\s*:\s*(?P<label>\S+)')
    children = {}
    parent = {}
    top = []
    parents = [None]
    for raw in tree_str.splitlines():
        # RMG remove_comment_from_line: cut at the first '//'
        i = raw.find('//')
        line = (raw[:i] if i >= 0 else raw).strip()
        if not line:
            continue
        m = parser.match(line)
        if not m:
            raise FamilyLoadError("Couldn't parse tree line '%s'" % line)
        level = int(m.group('level'))
        label = m.group('label')
        if len(parents) < level:
            raise FamilyLoadError(
                'Invalid level %d in tree line %r' % (level, line))
        while len(parents) > level:
            parents.pop()
        par = parents[level - 1] if len(parents) > 0 else None
        if par is not None:
            children.setdefault(par, []).append(label)
            parent[label] = par
        else:
            top.append(label)
            parent[label] = None
        parents.append(label)
    return children, parent, top


