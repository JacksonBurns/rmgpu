#!/usr/bin/env python
"""job-04 gate - THE PoC THESIS TEST (PLAN.md 1, 10-Phase 1).

Measures whether rmgpu's ML estimators (the two vendored checkpoints) match
RMG-Py's library+GA+rate-rules accuracy. Rigorous and honest: the deliverable
is the measured error distribution, not a smoothed green. A RED gate is a
VALID PoC OUTCOME (PLAN 13 risk 1) - reported with full numbers, recorded in
STATUS, and left to the user (step-06: "Do NOT paper over it").

Four checks (gate definition, job-04):
  (4) Checkpoint round-trip: BOTH vendored checkpoints reproduce the step-01
      reference predictions via rmgpu.ml.base (non-circular: the baseline was
      generated by models/predict.py itself).
  (1) Coverage: over the union of species in examples
      {superminimal, c3h4, minimal, minimal_ml, ethane-oxidation} + all
      primaryThermoLibrary species (thermo) and the c3h4/superminimal
      mechanism-relevant reaction set + depository subset (kinetics):
      % resolved by the resolvers + the unresolved list with reasons.
  (2) Accuracy vs RMG-Py on covered species (cap ~500, stratified by class):
      Hf298/S298/Cp(300,600,1000) - N, mean abs err, median, max, p95 +
      histograms + per-class and per-sign breakdowns;
      HPL k(T): log10(k_rmgpu/k_rmg) at 300/600/1000 K, overall + per bucket.
  (3) No-fallback proof: the resolvers (rmgpu.data.estimation) are
      instrumented (EstimationCounts); library + ML + coverage == total,
      and NO other branch exists in the code (PLAN 14). The split is reported.

The RMG-Py reference comes from gates/baselines/thesis_test/ (thermo.json,
reactions.json), generated by scripts/reference_props.py in rmg_env and
committed. The gate never re-derives the reference.

UNIT CONVENTION (verified, not assumed):
  thermo  Hf298 J/mol, S298 J/(mol*K), Cp J/(mol*K) - both sides SI.
  kinetics The baseline's k(T) is SI (m^3/(mol*s) bimolecular,
    cm^6->m^6... i.e. get_rate_coefficient's SI output - verified in rmg_env:
    A=(1e13, cm^3/(mol*s)), n=0, Ea=0 gives k(300)=1e7, i.e. 1e13*1e-6).
    The rmgpu ML side emits A in CGS cm^3/(mol*s) (per-site, PLAN 3b); the
    gate converts k_cgs -> k_si with 10**(-6*(molecularity-1)) before
    comparing log10(k_rmgpu/k_rmg).

KNOWN ARTIFACTS (reported, not hidden):
  * The thermo checkpoint's H298 target is 10^(log-space) - ALWAYS POSITIVE
    by construction (trained on rmgdb species with positive H298). Species
    whose RMG-Py reference Hf298 is NEGATIVE (most stable molecules) are
    structurally outside the model's output domain; their dHf298 is reported
    separately (per-sign breakdown) as the PLAN 3b finding.
  * The ML branch's Cp(T) passes through the estimator's COARSE Wilhoit fit
    (rmgpu/ml/thermo_estimator._fit_wilhoit: a_i=0, B=500) - a documented
    simplification. The gate reports the estimator's Cp_model values (what a
    mechanism would use) AND a raw-grid diagnostic (the checkpoint's own
    7-point grid at 300/600/1000) so the fit-smoothing can be separated
    from model error.
  * The kinetics checkpoint is not bit-stable in-process (drift ~1.6e-2
    ABSOLUTE on the linear Ea column; step-05 finding). 0.0156 J/mol on Ea
    is negligible for k(T) at 300-1000 K; the round-trip tolerance (atol
    1e-4) absorbs it with margin.

Run:  /home/jackson/miniforge3/envs/rmgpu/bin/python gates/gate_04.py
Writes reports/gate_04_results.json (full numbers) + a console summary.
Exit code: 0 = PASS, 2 = RED.
"""
