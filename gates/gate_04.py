class _MLBundle:
    """The estimators as the resolvers expect them: an object with
    ``.thermo`` (ThermoML) and ``.kinetics`` (KineticsML) attributes.

    KineticsML's constructor already builds a ThermoML for its covers()
    check - reuse it so the thermo checkpoint is loaded exactly once.
    """

    def __init__(self):
        self.kinetics = KineticsML()
        self.thermo = self.kinetics.thermo_ml


def main() -> int:
    t_start = time.time()
    ref_thermo = json.loads(THERMO_REF.read_text())
    ref_rxns = json.loads(RXN_REF.read_text())
    species_list = [
        {"smiles": smi, "label": v["label"], "in_ptl": v["in_ptl"],
         "class": v["class"]}
        for smi, v in ref_thermo["species"].items()
    ]

    print("[gate_04] loading estimators (real vendored checkpoints)...",
          flush=True)
    ml_bundle = _MLBundle()
    db = Databases.from_config({
        "thermo_libraries": THERMO_LIBRARIES,
        "reaction_libraries": REACTION_LIBRARIES,
    })

    print("[gate_04] check 4: checkpoint round-trip", flush=True)
    rt = check_roundtrip(ml_bundle.thermo.ckpt, ml_bundle.kinetics.ckpt)

    print(f"[gate_04] check 1/3 thermo: coverage + no-fallback "
          f"({len(species_list)} species)", flush=True)
    th = check_thermo(species_list, db.thermo, ml_bundle, ref_thermo)

    print(f"[gate_04] check 1/3 kinetics: coverage + no-fallback "
          f"({len(ref_rxns['reactions'])} reactions)", flush=True)
    ki = check_kinetics(ref_rxns, db.kinetics, ml_bundle)

    # --- verdict -----------------------------------------------------------
    checks = {
        "checkpoint_roundtrip": rt["pass"],
        "thermo_coverage": th["coverage"]["coverage_pct"] >= TH_COV_MIN,
        "kinetics_coverage": ki["coverage"]["coverage_pct"] >= KIN_COV_MIN,
        "no_fallback_thermo": (th["no_fallback"]["total"] == len(species_list)
                               and th["no_fallback"]["library_hits"]
                               + th["no_fallback"]["ml_hits"]
                               + th["no_fallback"]["coverage_errors"]
                               == th["no_fallback"]["total"]),
        "no_fallback_kinetics": (ki["no_fallback"]["total"] == len(
            ref_rxns["reactions"])
            and ki["no_fallback"]["library_hits"]
            + ki["no_fallback"]["ml_hits"]
            + ki["no_fallback"]["coverage_errors"]
            == ki["no_fallback"]["total"]),
    }
    acc_t = th["accuracy_ml_vs_legacy"]
    checks["accuracy_hf298"] = acc_t["dhf298_J_mol"].get("p95_abs", 0) \
        <= HERR_P95_MAX
    checks["accuracy_s298"] = acc_t["ds298_J_molK"].get("p95_abs", 0) \
        <= SERR_P95_MAX
    checks["accuracy_cp"] = acc_t["dcp_J_molK"].get("p95_abs", 0) \
        <= CPERR_P95_MAX
    for T in T_LIST:
        key = f"log10_k_ratio_{int(T)}"
        checks[f"accuracy_kT_{int(T)}"] = (
            ki["accuracy_ml_vs_legacy"][key].get("p95_abs", 0) <= KLOG_P95_MAX)

    overall = all(checks.values())
    results = {
        "gate": "job-04 thesis test (PoC premise: ML matches legacy accuracy)",
        "overall": "PASS" if overall else "RED",
        "checks": checks,
        "thresholds": {
            "thermo_coverage_min": TH_COV_MIN,
            "kinetics_coverage_min": KIN_COV_MIN,
            "hf298_p95_max_J_mol": HERR_P95_MAX,
            "s298_p95_max_J_molK": SERR_P95_MAX,
            "cp_p95_max_J_molK": CPERR_P95_MAX,
            "k_log10_p95_max": KLOG_P95_MAX,
        },
        "checkpoint_roundtrip": rt,
        "thermo": th,
        "kinetics": ki,
        "elapsed_s": round(time.time() - t_start, 1),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(results, indent=2))

    # --- console summary ---------------------------------------------------
