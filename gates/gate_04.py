def _ml_k_si(A_cgs: float, n: float, Ea: float, T: float, molec: int) -> float:
    """k(T) in SI from the ML's CGS per-site A (PLAN 3b boundary).

    CGS -> SI: cm^3/(mol*s) -> m^3/(mol*s) is 1e-6; cm^6/(mol^2*s) ->
    m^6/(mol^2*s) is 1e-12; i.e. 10**(-6*(molecularity-1)).
    """
    k_cgs = A_cgs * (T / 1.0) ** n * np.exp(-Ea / (R * T))
    return k_cgs * 10.0 ** (-6 * (molec - 1))


def check_kinetics(ref_rxns: dict, kinetics_db, ml_bundle) -> dict:
    t0 = time.time()
    counts = EstimationCounts()
    reactions = ref_rxns["reactions"]
    n = len(reactions)

    resolver = {}
    model_cov = 0
    for i, (smi, rec) in enumerate(reactions.items()):
        try:
            if ml_bundle.kinetics.covers(smi):
                model_cov += 1
        except Exception:
            pass
        rxn = {
            "label": smi[:60],
            "reactants": [{"label": f"r{j}", "smiles": s}
                          for j, s in enumerate(rec["reactants"])],
            "products": [{"label": f"p{j}", "smiles": s}
                         for j, s in enumerate(rec["products"])],
            "reaction_smiles": smi,
        }
        try:
            model, _deg = estimate_kinetics(
                rxn, kinetics_db, ml_bundle, counts=counts,
                libraries=REACTION_LIBRARIES, degeneracy=1.0)
            # the ML branch tags its Arrhenius comment "ML estimate, ...";
            # library hits carry rmgdb's stored comment
            comment = str(getattr(model, "comment", ""))
            resolver[smi] = {
                "status": "ml" if comment.startswith("ML") else "library",
                "A": float(model.A),
                "n": float(model.n),
                "Ea_J_mol": float(model.Ea),
            }
        except MLCoverageError as e:
            resolver[smi] = {"status": "coverage_error", "reason": str(e)}
        except Exception as e:
            resolver[smi] = {"status": "error",
                             "reason": f"{type(e).__name__}: {e}"}
        if (i + 1) % 25 == 0:
            print(f"[gate_04 kinetics] {i + 1}/{n} "
                  f"({time.time() - t0:.0f}s)", flush=True)

    covered = {s for s, r in resolver.items() if r["status"] in ("library", "ml")}
    cov_pct = len(covered) / n

    # check 2: accuracy of the ML k(T) vs the reference (SI).
    # Only ML-resolved reactions: the thesis is ML-vs-legacy, and library
    # hits have no ML value by construction (resolver short-circuits).
    logs = {T: [] for T in T_LIST}
    per_bucket = {}
    for smi, rec in reactions.items():
        r = resolver.get(smi, {})
        if r.get("status") != "ml":
            continue
        molec = rec["molecularity"]
        for T in T_LIST:
            k_ref = rec.get(f"k{int(T)}")
            if k_ref is None or k_ref <= 0:
                continue
            k_rmgpu = _ml_k_si(r["A"], r["n"], r["Ea_J_mol"], T, molec)
            if k_rmgpu <= 0:
                continue
            ratio = float(np.log10(k_rmgpu / k_ref))
            logs[T].append(ratio)
            per_bucket.setdefault(rec["bucket"], {}).setdefault(
                T, []).append(ratio)

    out = {
        "n_reactions": n,
        "coverage": {
            "model_covers": int(model_cov),
            "resolver_covered": int(len(covered)),
            "coverage_pct": round(cov_pct, 4),
            "uncovered": [
                {"reaction_smiles": s,
                 "bucket": reactions[s]["bucket"],
                 "reason": resolver[s].get("reason", "")}
                for s in sorted(set(resolver) - covered)
            ],
        },
        "no_fallback": counts.as_dict(),
        "accuracy_ml_vs_legacy": {
            f"log10_k_ratio_{int(T)}": stats(np.asarray(logs[T]))
            for T in T_LIST
        },
        "per_bucket": {
            b: {f"log10_k_ratio_{int(T)}": stats(np.asarray(v[T]))
                for T in T_LIST if T in v}
            for b, v in sorted(per_bucket.items())
        },
        "histogram_log10_k_ratio_600K": hist_binning(np.asarray(logs[600.0])),
        "elapsed_s": round(time.time() - t0, 1),
    }
    return out


