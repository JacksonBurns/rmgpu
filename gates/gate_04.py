def check_roundtrip(ckpt_t, ckpt_k) -> dict:
    t0 = time.time()
    ref = json.loads(REF_PRED.read_text())
    out: dict = {"tol": "rtol=1e-6, atol=1e-4 per element (absorbs the known "
                        "in-process ~1.6e-2-absolute Ea flake documented in step-05)"}

    mol_refs = ref["molecules"]["smiles"]
    pts = [chemprop_data.MoleculeDatapoint.from_smi(s, keep_h=True, add_h=True)
           for s in mol_refs]
    raw = ckpt_t.predict_raw(pts, batch_size=8)
    ok = True
    maxdiff = 0.0
    for i, smi in enumerate(mol_refs):
        for j, target in enumerate(ckpt_t.targets):
            expected = ref["molecules"]["rows"][smi][target]
            actual = float(raw[i, j])
            if not np.allclose(actual, expected, rtol=1e-6, atol=1e-4):
                ok = False
                out.setdefault("failures", []).append(
                    f"thermo {smi} {target}: {actual!r} vs {expected!r}")
            maxdiff = max(maxdiff, abs(actual - expected))
    out["thermo"] = {
        "checkpoint": THERMO_CKPT_PATH.name,
        "n_molecules": len(mol_refs),
        "max_abs_diff_raw": maxdiff,
        "pass": ok,
    }

    rxn_refs = ref["reactions"]["smiles"]
    pts = [chemprop_data.ReactionDatapoint.from_smi(s, keep_h=True, add_h=True)
           for s in rxn_refs]
    raw = ckpt_k.predict_raw(pts, batch_size=8)
    k_ok = True
    maxdiff = 0.0
    for i, smi in enumerate(rxn_refs):
        for j, target in enumerate(ckpt_k.targets):
            expected = ref["reactions"]["rows"][smi][target]
            actual = float(raw[i, j])
            if not np.allclose(actual, expected, rtol=1e-6, atol=1e-4):
                k_ok = False
                out.setdefault("failures", []).append(
                    f"kinetics {smi[:40]}... {target}: {actual!r} vs "
                    f"{expected!r}")
            maxdiff = max(maxdiff, abs(actual - expected))
    out["kinetics"] = {
        "checkpoint": KINETICS_CKPT_PATH.name,
        "n_reactions": len(rxn_refs),
        "max_abs_diff_raw": maxdiff,
        "pass": k_ok,
    }
    out["elapsed_s"] = round(time.time() - t0, 1)
    out["pass"] = ok and k_ok
    return out


