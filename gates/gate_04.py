def stats(arr) -> dict:
    a = np.asarray(arr, dtype=np.float64)
    if a.size == 0:
        return {"N": 0}
    return {
        "N": int(a.size),
        "mean_abs": float(np.mean(np.abs(a))),
        "median_abs": float(np.median(np.abs(a))),
        "max_abs": float(np.max(np.abs(a))),
        "p95_abs": float(np.percentile(np.abs(a), 95)),
        "mean": float(np.mean(a)),
        "median": float(np.median(a)),
        "max": float(np.max(a)),
        "min": float(np.min(a)),
    }


def hist_binning(arr, bins: int = 20) -> dict:
    """ASCII histogram (20 bins) for the report."""
    a = np.asarray(arr, dtype=np.float64)
    if a.size == 0:
        return {}
    counts, edges = np.histogram(a, bins=bins)
    top = int(np.max(counts)) or 1
    lines = []
    for i, c in enumerate(counts):
        lo, hi = edges[i], edges[i + 1]
        bar = "#" * int(40 * c / top)
        lines.append(f"  [{lo:10.3g}, {hi:10.3g}) {c:5d} |{bar}")
    return {"min": float(a.min()), "max": float(a.max()),
            "histogram": "\n".join(lines)}


