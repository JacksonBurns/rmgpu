def check_thermo(species_list: list[dict], thermo_db, ml_bundle,
                 ref_thermo: dict) -> dict:
    t0 = time.time()
    counts = EstimationCounts()
    n = len(species_list)
    if n > CAP_SPECIES:  # stratified subsample (not needed: set < cap)
        raise RuntimeError("species set exceeds the gate cap")

    resolver = {}   # check 1+3: what the resolvers do (runtime behavior)
    model_cov = 0
    for i, sp in enumerate(species_list):
        smiles, label = sp["smiles"], sp["label"]
        try:
            if ml_bundle.thermo.covers(smiles):
                model_cov += 1
        except Exception:
            pass
        try:
            pred = estimate_thermo(
                {"label": label, "smiles": smiles},
                thermo_db, ml_bundle, counts=counts,
                libraries=THERMO_LIBRARIES)
            resolver[smiles] = {
                "status": pred.uncertainties.get("source", "library"),
                "Hf298": float(pred.Hf298),
                "S298": float(pred.S298),
                "Cp300": float(pred.Cp_model.get_heat_capacity(300.0)),
                "Cp600": float(pred.Cp_model.get_heat_capacity(600.0)),
                "Cp1000": float(pred.Cp_model.get_heat_capacity(1000.0)),
            }
        except MLCoverageError as e:
            resolver[smiles] = {"status": "coverage_error", "reason": str(e)}
        except Exception as e:
            resolver[smiles] = {"status": "error",
                                "reason": f"{type(e).__name__}: {e}"}
        if (i + 1) % 10 == 0:
            print(f"[gate_04 thermo] {i + 1}/{n} "
                  f"({time.time() - t0:.0f}s)", flush=True)

    covered = {s for s, r in resolver.items() if r["status"] in ("library", "ml")}
    cov_pct = len(covered) / n
    by_label = {sp["smiles"]: sp for sp in species_list}

    # check 2: accuracy of the ML estimator vs the RMG-Py reference
    # (the thesis: does ML match legacy library+GA accuracy)
    dhf, dsl, dcp = [], [], []
    dhf_in_domain = []  # ref_Hf298 > 0 only: the model's positive-output domain
    dcp_raw = []  # diagnostic: the checkpoint's RAW 7-point grid (no fit)
    per_class = {}
    per_sign = {"ref_Hf298_negative": [], "ref_Hf298_nonnegative": []}
    ml_fail = []
    for sp in species_list:
        smiles = sp["smiles"]
        ref = ref_thermo["species"].get(smiles)
        if ref is None or "error" in ref:
            continue
        try:
            p = ml_bundle.thermo.predict(smiles)
        except MLCoverageError as e:
            ml_fail.append({"smiles": smiles, "reason": str(e)})
            continue
        dh = p.Hf298 - ref["Hf298"]
        ds = p.S298 - ref["S298"]
        # estimator Cp (what a mechanism would consume)
        dc = [p.Cp_model.get_heat_capacity(T) - ref[f"Cp{int(T)}"]
              for T in T_LIST]
        # diagnostic: raw checkpoint grid at the same temperatures
        raw_cp = np.asarray(p.Cp_model.Cp, dtype=np.float64)
        dc_raw = [float(raw_cp[CP_GRID_IDX[int(T)]]) - ref[f"Cp{int(T)}"]
                  for T in T_LIST]
        cls = ref["class"]
        per_class.setdefault(cls, {"n": 0, "dhf": [], "ds": [], "dcp": []})
        per_class[cls]["n"] += 1
        per_class[cls]["dhf"].append(dh)
        per_class[cls]["ds"].append(ds)
        per_class[cls]["dcp"].extend(dc)
        sig = ("ref_Hf298_negative" if ref["Hf298"] < 0
               else "ref_Hf298_nonnegative")
        per_sign[sig].append(dh)
        dhf.append(dh)
        dsl.append(ds)
        dcp.extend(dc)
        dcp_raw.extend(dc_raw)
        if ref["Hf298"] > 0:  # the model's H298 output (10^pred) can only be
            # positive; ref_Hf298 > 0 is its training domain
            dhf_in_domain.append(dh)
    dhf_in_domain_arr = np.asarray(dhf_in_domain)

    out = {
        "n_species": n,
        "coverage": {
            "model_covers": int(model_cov),
            "resolver_covered": int(len(covered)),
            "coverage_pct": round(cov_pct, 4),
            "uncovered": [
                {"smiles": s, "label": by_label[s]["label"],
                 "class": by_label[s]["class"],
                 "reason": resolver[s].get("reason", "")}
                for s in sorted(set(resolver) - covered)
            ],
        },
        "no_fallback": counts.as_dict(),
        "accuracy_ml_vs_legacy": {
            "dhf298_J_mol": stats(dhf),
            "ds298_J_molK": stats(dsl),
            "dcp_J_molK": stats(dcp),
            "dcp_raw_grid_J_molK_diagnostic": stats(dcp_raw),
            "dhf298_kJ_mol": {k: (v / 1000.0 if isinstance(v, float) else v)
                              for k, v in stats(dhf).items()},
            "histogram_dhf298_kJ_mol": hist_binning(np.asarray(dhf) / 1000.0),
            "per_class": {
                c: {"n": v["n"],
                    "dhf298_kJ_mol": stats(np.asarray(v["dhf"]) / 1000.0),
                    "ds298_J_molK": stats(np.asarray(v["ds"])),
                    "dcp_J_molK": stats(np.asarray(v["dcp"]))}
                for c, v in sorted(per_class.items())
            },
            # the PLAN 3b finding: the model's H298 output is always
            # positive (10^log-space, trained on positive-H298 species), so
            # negative-Hf298 species are outside its domain by construction
            "dhf298_by_ref_sign_kJ_mol": {
                s: stats(np.asarray(v) / 1000.0) for s, v in per_sign.items()
            },
            # the model's output (10^pred) is positive by construction; the
            # ref_Hf298 > 0 subset is its training domain, where the error is
            # the honest in-domain accuracy (the PLAN 3b boundary finding)
            "dhf298_in_domain_ref_positive_kJ_mol": stats(
                dhf_in_domain_arr / 1000.0),
            "ml_coverage_failures": ml_fail,
        },
        "elapsed_s": round(time.time() - t0, 1),
    }
    return out


