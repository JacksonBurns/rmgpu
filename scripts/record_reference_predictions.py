#!/usr/bin/env python3
"""Record reference predictions for the two vendored checkpoints (job-04/step-01).

NON-CIRCULAR BY DESIGN: the baseline is generated with models/predict.py's OWN
pattern (the model team's predictor classes, run directly) - NOT rmgpu.ml.base.
Steps 02/03 and gate_04 assert that rmgpu.ml.base reproduces these values, so
the round-trip checks the model team's own output, not base.py's own output.

Fixed set:
  molecules: CC, CCC, C[CH]CC  (fixed by the step file)
  reactions: the two atom-mapped reaction SMILES from models/predict.py's
    __main__ - extracted from that file's AST at run time (never re-typed, so
    the inputs can't drift from the model team's own demo).

Output: gates/baselines/job04/reference_predictions.json - the raw
(model-native, log10-space) predictions at full float precision. Re-runnable
and idempotent: re-running rewrites the file in place; predictions are
deterministic given the checkpoint, so a re-run either confirms the baseline
unchanged or loudly reports a value drift (a finding).

Run: /home/jackson/miniforge3/envs/rmgpu/bin/python scripts/record_reference_predictions.py
"""
import ast
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MODELS_DIR = REPO_ROOT / "models"
OUT = REPO_ROOT / "gates" / "baselines" / "job04" / "reference_predictions.json"

# LOAD-PATH CONSTRAINT: the checkpoints pickle-reference the top-level module
# `models` (models.BoundedOutputTransform / models.HuberMetric). models/ has
# no __init__.py, so the models/ DIRECTORY ITSELF must be on sys.path for
# `import models` to resolve to models/models.py. (Same mechanism models/
# predict.py itself relies on - it does `from models import ...`.)
sys.path.insert(0, str(MODELS_DIR))

import predict  # noqa: E402  models/predict.py - the model team's code


THERMO_CKPT = MODELS_DIR / "chemeleon_thermo_662946.ckpt"
KINETICS_CKPT = MODELS_DIR / "chemprop_kinetics_662946.ckpt"

THERMO_SMILES = ["CC", "CCC", "C[CH]CC"]


def extract_main_reactions(predict_py: Path) -> list[str]:
    """Pull the reaction SMILES list from models/predict.py's __main__ via AST.

    Matches `if __name__ == "__main__":` and returns the literal list passed to
    the `predictor_kinetics([...])` call inside it.
    """
    tree = ast.parse(predict_py.read_text())

    def is_main_test(node: ast.expr) -> bool:
        # __name__ == "__main__"
        if not isinstance(node, ast.Compare):
            return False
        if not (isinstance(node.left, ast.Name) and node.left.id == "__name__"):
            return False
        if not (len(node.ops) == 1 and isinstance(node.ops[0], ast.Eq)):
            return False
        comps = node.comparators
        return len(comps) == 1 and isinstance(comps[0], ast.Constant) \
            and comps[0].value == "__main__"

    for node in ast.walk(tree):
        if isinstance(node, ast.If) and is_main_test(node.test):
            for sub in ast.walk(node):
                if (isinstance(sub, ast.Call)
                        and isinstance(sub.func, ast.Name)
                        and sub.func.id == "predictor_kinetics"
                        and sub.args
                        and isinstance(sub.args[0], ast.List)
                        and all(isinstance(el, ast.Constant)
                                and isinstance(el.value, str)
                                for el in sub.args[0].elts)):
                    return [el.value for el in sub.args[0].elts]
    raise RuntimeError("could not find predictor_kinetics([...]) in __main__")


def _rows_from_frame(df, key_col):
    """DataFrame (with a key column of raw smiles) -> {smiles: {target: float}}."""
    d = df.set_index(key_col)
    return {
        str(k): {col: float(v) for col, v in row.items()}
        for k, row in d.iterrows()
    }


def main():
    rxn_smiles = extract_main_reactions(MODELS_DIR / "predict.py")
    if len(rxn_smiles) != 2 or any(">>" not in s for s in rxn_smiles):
        raise RuntimeError(f"unexpected reaction set extracted: {rxn_smiles!r}")

    thermo = predict.CheMeleonThermoPredictor(ckpt_path=THERMO_CKPT)
    df_thermo = thermo(THERMO_SMILES)

    kinetics = predict.ChempropKineticsPredictor(ckpt_path=KINETICS_CKPT)
    df_kinetics = kinetics(rxn_smiles)

    baseline = {
        "description": (
            "Reference raw predictions for the two vendored checkpoints, "
            "generated by models/predict.py's own pattern (scripts/"
            "record_reference_predictions.py). 'Raw' = model-native log10-space "
            "outputs at full float precision. Steps 02/03 and gate_04 assert "
            "rmgpu.ml.base reproduces these values (tol 1e-4)."
        ),
        "molecules": {
            "checkpoint": "models/chemeleon_thermo_662946.ckpt",
            "smiles": THERMO_SMILES,
            "targets": [c for c in df_thermo.columns if c != "smiles"],
            "rows": _rows_from_frame(df_thermo, "smiles"),
        },
        "reactions": {
            "checkpoint": "models/chemprop_kinetics_662946.ckpt",
            "smiles": rxn_smiles,
            "targets": [c for c in df_kinetics.columns if c != "rxn_smiles"],
            "rows": _rows_from_frame(df_kinetics, "rxn_smiles"),
        },
    }

    payload = json.dumps(baseline, indent=2)

    if OUT.exists():
        old = OUT.read_text().strip()
        if old == payload.strip():
            print(f"baseline unchanged: {OUT.relative_to(REPO_ROOT)}")
            return 0
        print(f"WARNING: baseline CHANGED vs committed {OUT.relative_to(REPO_ROOT)}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(payload + "\n")

    for name, section in (("molecules", baseline["molecules"]),
                          ("reactions", baseline["reactions"])):
        print(f"\n{name} ({section['checkpoint']}):")
        for smi, vals in section["rows"].items():
            shown = ", ".join(f"{t}={v:.6f}" for t, v in vals.items())
            print(f"  {smi[:72]}{'...' if len(smi) > 72 else ''}\n    {shown}")
    print(f"\nwrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
